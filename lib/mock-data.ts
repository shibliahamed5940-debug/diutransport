export function getMockBusesWithRelations(): BusWithRelations[] {
  return mockBuses.map((bus) => ({
    ...bus,
    route: mockRoutes.find((r) => r.id === bus.route_id) ?? null,
    driver: mockStaff.find((s) => s.id === bus.driver_id) ?? null,
    helper: mockStaff.find((s) => s.id === bus.helper_id) ?? null,
  }));
}

export function getMockSchedulesWithRelations(): ScheduleWithRelations[] {
  return mockSchedules.map((schedule) => ({
    ...schedule,
    bus: mockBuses.find((b) => b.id === schedule.bus_id) ?? null,
    route: mockRoutes.find((r) => r.id === schedule.route_id) ?? null,
  }));
}
